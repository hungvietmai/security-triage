"""The worker's CWE-22 query pack must stay byte-identical to the evaluated v0.2 research pack."""

from __future__ import annotations

import hashlib
import json
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PACK = ROOT / "rules/codeql/path-traversal-v0.2"
PILOT = ROOT / "experiments/owasp-bp-pilot"
WAVE_C = ROOT / "experiments/wave-c"


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _manifest(path: Path) -> dict[str, str]:
    entries = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        digest, _, name = line.partition("  ")
        if len(digest) == 64 and name:
            entries[name] = digest
    return entries


class ProductPackProvenanceTests(unittest.TestCase):
    def test_library_and_evidence_table_match_the_v02_freeze(self) -> None:
        frozen = _manifest(PILOT / "FREEZE_v0.2_postformat.sha256")
        for name in ("SafetyEvidence.qll", "qlpack.yml", "table/Evidence.ql"):
            with self.subTest(name=name):
                self.assertEqual(_sha256(PACK / name), frozen[f"ql_v02/{name}"])

    def test_queries_and_lock_match_the_wave_c_execution(self) -> None:
        # The queries are generated by the frozen gen.py; Wave C recorded the bytes it ran.
        toolchain = json.loads((WAVE_C / "toolchain.lock.json").read_text(encoding="utf-8"))
        executed = toolchain["file_hashes"]
        for query in ("cwe22_none.ql", "cwe22_all.ql"):
            with self.subTest(query=query):
                self.assertEqual(
                    _sha256(PACK / "queries" / query),
                    executed[f"artifacts/wave-c/toolchain/v02/queries/{query}"],
                )
        locked = _manifest(WAVE_C / "EXECUTION_LOCK.sha256")
        self.assertEqual(
            _sha256(PACK / "codeql-pack.lock.yml"),
            locked["experiments/wave-c/pack-locks/v02.lock.yml"],
        )


if __name__ == "__main__":
    unittest.main()
